import torch.nn.functional as F

def compute_trajectory_straightness(records):
    """
    Computes the cosine similarity between consecutive update vectors across depth.
    High alignment = Low curvature (Geodesic behavior).
    """
    layer_alignments = defaultdict(list)

    for rec in records:
        # layers shape: [num_layers, seq_len, hidden_dim]
        # We assume 'layers' is a list of numpy arrays

        # Stack layers into tensor: (L, Seq, D)
        hs = np.stack(rec["layers"])
        L, S, D = hs.shape

        # Focus on the final token used for generation prompt
        # shape: (L, D)
        h_final = hs[:, -1, :]

        # Compute update vectors: delta_l = h_{l+1} - h_l
        # shape: (L-1, D)
        deltas = h_final[1:] - h_final[:-1]

        # Compute cosine sim between delta_l and delta_{l+1}
        # We convert to torch tensors for F.cosine_similarity
        deltas_t = torch.tensor(deltas) # (L-1, D)

        # We want cosine sim between row i and row i+1
        # v1: vectors at l=0..L-3
        # v2: vectors at l=1..L-2
        v1 = deltas_t[:-1]
        v2 = deltas_t[1:]

        sims = F.cosine_similarity(v1, v2, dim=1) # (L-2,)

        for l, s in enumerate(sims):
            layer_alignments[l].append(s.item())

    # Aggregating results
    depths = sorted(layer_alignments.keys())
    means = [np.mean(layer_alignments[l]) for l in depths]
    stds = [np.std(layer_alignments[l]) for l in depths]

    return depths, means, stds

