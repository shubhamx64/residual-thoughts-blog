def get_steered_embedding(prompt, direction_vec, layers, alpha):
    """
    Hooks the model, runs the prompt, and returns the FINAL hidden state
    of the LAST layer (or the layer after steering).
    """
    enc = tok(prompt, return_tensors="pt").to(device)

    final_layer_idx = NUM_LAYERS - 1
    captured_state = None

    def capture_hook(module, inputs, output):
        nonlocal captured_state
        # output[0] is (Batch, Seq, Dim)
        # IMPORTANT: Cast to float32 before detaching to numpy to avoid BFloat16 error
        captured_state = output[0][0, -1, :].to(torch.float32).detach().cpu().numpy()

    # Register hook on final layer
    handle = get_transformer_layers(model)[final_layer_idx].register_forward_hook(capture_hook)

    try:
        # Run with steering
        with corridor_shift(model, layers, direction_vec, alpha=alpha):
            model(**enc)
    finally:
        handle.remove()

    return captured_state

