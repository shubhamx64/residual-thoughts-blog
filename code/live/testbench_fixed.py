@torch.inference_mode()
def generate_with_corridor_shift(prompt: str, vec_np: np.ndarray,
                                 layer_indices: List[int], alpha: float = 1.0,
                                 max_new: int = MAX_NEW) -> str:
    enc = tok(prompt, return_tensors="pt").to(device)
    prompt_len = enc["input_ids"].shape[1]

    with corridor_shift(model, layer_indices, vec_np, alpha=alpha, prompt_len=prompt_len):
        gen_ids = model.generate(
            **enc,
            do_sample=False,
            max_new_tokens=max_new,
            use_cache=False,
        )[0]

    completion = tok.decode(gen_ids[prompt_len:], skip_special_tokens=True)
    return completion

